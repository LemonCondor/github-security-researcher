"""Read-only collection of organisation and repository metadata (two passes).

Pass 1 (cheap): org profile + paginated public repo listing, most recently pushed first.
Pass 2 (bounded, top-K per org): file tree, languages, community profile, recent commits and closed PRs,
CONTRIBUTING / AI-policy text. Nothing is cloned, built or executed; every fact keeps its API source.
A field that could not be collected is simply absent (= unknown), never guessed.
"""
from __future__ import annotations

import base64
import re
from datetime import datetime, timedelta, timezone

from .api import DiscoveryError, ReadOnlyGitHub

LISTING = "api:orgs/{org}/repos"
EXTERNAL_ASSOC = {"CONTRIBUTOR", "FIRST_TIME_CONTRIBUTOR", "FIRST_TIMER", "NONE"}
TEST_RE = re.compile(r"(^|/)(tests?|testing|spec|__tests__|testdata)(/|$)|_test\.go$|(^|/)test_[^/]+\.py$|"
                     r"[^/]+_test\.py$|\.(test|spec)\.[jt]sx?$|(^|/)src/test/", re.I)
CI_RE = re.compile(r"^\.github/workflows/[^/]+\.ya?ml$|^\.travis\.yml$|^\.gitlab-ci\.yml$|^\.circleci/|"
                   r"^Jenkinsfile$|^azure-pipelines\.ya?ml$|^\.drone\.yml$|^\.buildkite/|^prow/", re.I)
VENDOR_RE = re.compile(r"(^|/)(vendor|third_party|node_modules)/", re.I)
POLICY_FILES = re.compile(r"^(\.github/|docs/)?(CONTRIBUTING(\.md|\.rst|\.txt)?|AI[_-]?POLICY\.md|AGENTS\.md)$", re.I)
DOC_RE = re.compile(r"\.(md|markdown|rst|adoc|txt)$|(^|/)docs?/", re.I)
SOURCE_RE = re.compile(r"\.(go|py|js|jsx|ts|tsx|java|kt|scala|c|cc|cpp|cxx|h|hpp|rs|rb|php|cs|swift|m|sh|"
                       r"f90|f|jl|r|lua|pl|ex|exs|erl|hs|ml|dart|zig|vue|svelte)$", re.I)
ASSET_RE = re.compile(r"\.(png|jpe?g|gif|svg|ico|webp|bmp|tiff?|woff2?|ttf|otf|eot|pdf|mp[34]|wav|ogg|zip|gz|"
                      r"tgz|jar|bin|dat|nc|h5|fits)$", re.I)
GENERATED_DESC = re.compile(r"\b(auto-?generated|generated by|read-only mirror|mirror of)\b", re.I)


def code_share(paths: list[str]) -> float:
    """Source files / non-asset files (images, fonts, archives and binary data are ignored)."""
    text = [p for p in paths if not ASSET_RE.search(p)]
    return round(sum(1 for p in text if SOURCE_RE.search(p)) / len(text), 3) if text else 0.0


def _fact(value, source: str) -> dict:
    return {"value": value, "source": source}


def now_utc() -> datetime:
    return datetime.now(timezone.utc)


def org_profile(api: ReadOnlyGitHub, login: str) -> dict:
    d = api.get(f"orgs/{login}")
    return {"display_login": d.get("login") or login, "name": d.get("name"), "website": d.get("blog") or None,
            "domain_verified": d.get("is_verified"), "description": d.get("description"),
            "github_url": d.get("html_url"), "public_repos": d.get("public_repos")}


def list_repos(api: ReadOnlyGitHub, login: str, max_repos: int) -> list[dict]:
    return api.paginate(f"orgs/{login}/repos?type=public&sort=pushed&direction=desc", max_repos)


def listing_facts(raw: dict, login: str) -> dict:
    src = LISTING.format(org=login)
    lic = raw.get("license") or None
    keys = {"description": "description", "language": "language", "stars": "stargazers_count",
            "forks": "forks_count", "pushed_at": "pushed_at", "created_at": "created_at",
            "default_branch": "default_branch", "open_issues_and_prs": "open_issues_count",
            "archived": "archived", "disabled": "disabled", "fork": "fork", "is_template": "is_template",
            "mirror_url": "mirror_url", "visibility": "visibility", "size_kb": "size", "html_url": "html_url",
            "topics": "topics", "has_issues": "has_issues"}
    out = {k: _fact(raw.get(v), src) for k, v in keys.items() if v in raw}
    if "license" in raw:
        out["license"] = _fact((lic or {}).get("spdx_id") if lic else None, src)
    return out


def classify_ai_policy(text: str) -> tuple[str, str | None]:
    """(policy, excerpt). prohibited only when a refusal is stated without any allowance; a text that both
    allows AI and sets conditions (disclosure, no AI commit messages...) is 'conditions'."""
    if not text:
        return "none_found", None
    low = text.lower()
    ai = re.compile(r"\b(ai|a\.i\.|llms?|large language models?|copilot|chatgpt|generative|ai-assisted|"
                    r"ai-generated)\b")
    if not ai.search(low):
        return "none_found", None
    sentences = re.split(r"(?<=[.!?])\s+|\n{2,}", text)
    ai_sents = [s.strip() for s in sentences if ai.search(s.lower())]
    refuse = re.compile(r"(not (be )?(accepted|allowed|permitted|welcome)|prohibit|forbid|banned|will be "
                        r"(closed|rejected)|do not (accept|use|submit)|don't (accept|submit)|no ai)")
    allow = re.compile(r"(acceptable|allowed to use|may use|can use|is allowed|encourage|permitted|disclos|"
                       r"responsible for)")
    refusing = [s for s in ai_sents if refuse.search(s.lower())]
    allowing = [s for s in ai_sents if allow.search(s.lower())]
    if refusing and not allowing:
        return "prohibited", refusing[0][:240]
    if refusing or any("disclos" in s.lower() for s in ai_sents):
        return "conditions", (refusing or allowing or ai_sents)[0][:240]
    return "mentioned", ai_sents[0][:240]


def _text(api: ReadOnlyGitHub, full: str, path: str) -> str:
    d = api.get(f"repos/{full}/contents/{path}")
    if isinstance(d, dict) and d.get("encoding") == "base64":
        return base64.b64decode(d.get("content") or "").decode("utf-8", "replace")
    return ""


def enrich(api: ReadOnlyGitHub, full: str, facts: dict, now: datetime | None = None) -> tuple[dict, list[dict]]:
    """Second pass for one repo. Returns (new facts, errors). Each sub-call is independent: one failure leaves
    only its own fields unknown. RateLimited propagates (the run must stop)."""
    from .api import RateLimited
    now = now or now_utc()
    out: dict = {}
    errors: list[dict] = []
    branch = (facts.get("default_branch") or {}).get("value")

    def attempt(endpoint: str, fn):
        try:
            fn()
        except RateLimited:
            raise
        except DiscoveryError as e:
            errors.append({"endpoint": endpoint, "kind": e.kind, "message": str(e)[:300]})

    def tree():
        d = api.get(f"repos/{full}/git/trees/{branch}?recursive=1")
        paths = [t["path"] for t in d.get("tree", []) if t.get("type") == "blob"]
        src = "api:git/trees(recursive)"
        out["files"] = _fact(len(paths), src)
        out["tree_truncated"] = _fact(bool(d.get("truncated")), src)
        out["test_files"] = _fact(sum(1 for p in paths if TEST_RE.search(p)), src + " path heuristic")
        ci = sorted({p.split("/")[0] if not p.startswith(".github/") else ".github/workflows" for p in paths
                     if CI_RE.search(p)})
        out["ci"] = _fact(ci, src)
        vendored = sum(1 for p in paths if VENDOR_RE.search(p))
        out["vendored_share"] = _fact(round(vendored / len(paths), 3) if paths else 0.0, src + " path heuristic")
        docs = sum(1 for p in paths if DOC_RE.search(p))
        out["docs_share"] = _fact(round(docs / len(paths), 3) if paths else 0.0, src + " path heuristic")
        out["code_share"] = _fact(code_share(paths), src + " extension heuristic, assets excluded")
        out["policy_files"] = _fact([p for p in paths if POLICY_FILES.match(p)], src)

    def languages():
        d = api.get(f"repos/{full}/languages")
        total = sum(d.values()) if isinstance(d, dict) else 0
        out["code_bytes"] = _fact(total, "api:repos/languages")
        out["languages"] = _fact({k: round(v / total, 3) for k, v in sorted(d.items(), key=lambda kv: -kv[1])[:5]}
                                 if total else {}, "api:repos/languages")

    def community():
        d = api.get(f"repos/{full}/community/profile")
        files = d.get("files") or {}
        src = "api:community/profile"
        out["contributing"] = _fact(bool(files.get("contributing")), src)
        out["code_of_conduct"] = _fact(bool(files.get("code_of_conduct")), src)
        out["pr_template"] = _fact(bool(files.get("pull_request_template")), src)
        out["health_percentage"] = _fact(d.get("health_percentage"), src)

    def commits():
        since = (now - timedelta(days=90)).strftime("%Y-%m-%dT%H:%M:%SZ")
        d = api.get(f"repos/{full}/commits?since={since}&per_page=100")
        out["commits_90d"] = _fact(len(d) if isinstance(d, list) else None,
                                   "api:repos/commits (capped at 100)")

    def pulls():
        d = api.get(f"repos/{full}/pulls?state=closed&sort=updated&direction=desc&per_page=100")
        cutoff = now - timedelta(days=90)
        ext_merged = ext_closed = merged = 0
        for p in d if isinstance(d, list) else []:
            if (p.get("user") or {}).get("type") == "Bot":
                continue
            closed = p.get("closed_at")
            if not closed or datetime.fromisoformat(closed.replace("Z", "+00:00")) < cutoff:
                continue
            ext = p.get("author_association") in EXTERNAL_ASSOC
            if p.get("merged_at"):
                merged += 1
                ext_merged += ext
            elif ext:
                ext_closed += 1
        src = "api:repos/pulls?state=closed (last 100, 90 days, bots excluded)"
        out["merged_prs_90d"] = _fact(merged, src)
        out["external_merged_prs_90d"] = _fact(ext_merged, src)
        out["external_closed_unmerged_90d"] = _fact(ext_closed, src)

    def policy():
        paths = (out.get("policy_files") or {}).get("value")
        if paths is None:
            return
        texts = []
        for p in sorted(paths, key=lambda p: (not p.upper().endswith(("AI_POLICY.MD", "AI-POLICY.MD")), p))[:2]:
            texts.append(_text(api, full, p))
        joined = "\n\n".join(texts)
        if not paths:
            out["ai_policy"] = _fact("unknown", "no repo-level CONTRIBUTING/AI policy file (org-level not read)")
            return
        pol, excerpt = classify_ai_policy(joined)
        out["ai_policy"] = _fact(pol, f"api:contents {', '.join(paths[:2])} keyword heuristic")
        if excerpt:
            out["ai_policy_excerpt"] = _fact(excerpt, "quoted from the policy file")
        low = joined.lower()
        out["requires_cla"] = _fact(bool(re.search(r"\bcla\b|contributor license agreement", low)),
                                    "policy file keyword")
        out["requires_dco"] = _fact(bool(re.search(r"\bdco\b|signed-off-by|developer certificate of origin", low)),
                                    "policy file keyword")

    if branch:
        attempt("git/trees", tree)
    attempt("languages", languages)
    attempt("community/profile", community)
    attempt("commits", commits)
    attempt("pulls", pulls)
    attempt("contents(policy)", policy)
    return out, errors


def search_orgs(api: ReadOnlyGitHub, term: str, limit: int = 20) -> list[dict]:
    q = re.sub(r"[^A-Za-z0-9._-]", "", term)
    if not q:
        raise DiscoveryError(f"invalid search term {term!r}")
    items = api.paginate(f"search/users?q={q}+type:org", limit, key="items")
    return [{"login": i["login"], "github_url": i.get("html_url")} for i in items if i.get("type") == "Organization"]
